-- 실제 개인정보 대신 발표용 닉네임과 가상 정보만 사용하세요.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null check (char_length(nickname) between 1 and 20),
  age text default '선택 안 함',
  interest text,
  skills text,
  intro text,
  created_at timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  category text not null,
  scope text not null,
  members text,
  method text,
  description text not null,
  provide text,
  need text,
  author text,
  created_at timestamptz not null default now()
);

create table if not exists public.match_requests (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender_name text not null,
  message text not null,
  status text not null default '요청 대기',
  created_at timestamptz not null default now(),
  unique(project_id, sender_id)
);

alter table public.profiles enable row level security;
alter table public.projects enable row level security;
alter table public.match_requests enable row level security;

drop policy if exists "profiles readable by signed-in demo users" on public.profiles;
create policy "profiles readable by signed-in demo users" on public.profiles for select to authenticated using (true);
drop policy if exists "users create own profile" on public.profiles;
create policy "users create own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "projects readable by signed-in demo users" on public.projects;
create policy "projects readable by signed-in demo users" on public.projects for select to authenticated using (true);
drop policy if exists "users create own projects" on public.projects;
create policy "users create own projects" on public.projects for insert to authenticated with check (auth.uid() = owner_id);
drop policy if exists "owners update own projects" on public.projects;
create policy "owners update own projects" on public.projects for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
drop policy if exists "owners delete own projects" on public.projects;
create policy "owners delete own projects" on public.projects for delete to authenticated using (auth.uid() = owner_id);

drop policy if exists "participants read relevant requests" on public.match_requests;
create policy "participants read relevant requests" on public.match_requests for select to authenticated using (
  auth.uid() = sender_id or exists (select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid())
);
drop policy if exists "users create own requests" on public.match_requests;
create policy "users create own requests" on public.match_requests for insert to authenticated with check (auth.uid() = sender_id);
drop policy if exists "project owners update request status" on public.match_requests;
create policy "project owners update request status" on public.match_requests for update to authenticated using (
  exists (select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid())
) with check (
  exists (select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid())
);
